
"""Схемы популярных гитарных аккордов."""

# Струны от самой толстой к самой тонкой:
# E A D G B e
#
# X — струну не играть.
# 0 — открытая струна.
# Число — номер лада.

CHORD_SHAPES = {
    "C":   ["X", "3", "2", "0", "1", "0"],
    "Cm":  ["X", "3", "5", "5", "4", "3"],
    "D":   ["X", "X", "0", "2", "3", "2"],
    "Dm":  ["X", "X", "0", "2", "3", "1"],
    "E":   ["0", "2", "2", "1", "0", "0"],
    "Em":  ["0", "2", "2", "0", "0", "0"],
    "F":   ["1", "3", "3", "2", "1", "1"],
    "Fm":  ["1", "3", "3", "1", "1", "1"],
    "G":   ["3", "2", "0", "0", "0", "3"],
    "Gm":  ["3", "5", "5", "3", "3", "3"],
    "A":   ["X", "0", "2", "2", "2", "0"],
    "Am":  ["X", "0", "2", "2", "1", "0"],
    "B":   ["X", "2", "4", "4", "4", "2"],
    "Bm":  ["X", "2", "4", "4", "3", "2"],
    "C#":  ["X", "4", "6", "6", "6", "4"],
    "C#m": ["X", "4", "6", "6", "5", "4"],
    "D#":  ["X", "6", "8", "8", "8", "6"],
    "D#m": ["X", "6", "8", "8", "7", "6"],
    "F#":  ["2", "4", "4", "3", "2", "2"],
    "F#m": ["2", "4", "4", "2", "2", "2"],
    "G#":  ["4", "6", "6", "5", "4", "4"],
    "G#m": ["4", "6", "6", "4", "4", "4"],
    "Bb":  ["X", "1", "3", "3", "3", "1"],
    "Bbm": ["X", "1", "3", "3", "2", "1"],
}

# Альтернативные варианты, которые можно сыграть проще.
EASY_SHAPES = {
    "F":   ["X", "X", "3", "2", "1", "1"],
    "Fm":  ["X", "X", "3", "1", "1", "1"],
    "Bm":  ["X", "2", "4", "4", "3", "X"],
    "B":   ["X", "2", "4", "4", "4", "X"],
    "Gm":  ["X", "X", "5", "3", "3", "3"],
}


def get_chord_shape(chord, easy=False):
    """Возвращает аппликатуру аккорда."""
    if easy and chord in EASY_SHAPES:
        return EASY_SHAPES[chord]

    return CHORD_SHAPES.get(chord)


def format_chord_shape(chord, easy=False):
    """Создаёт текстовую схему аккорда."""
    shape = get_chord_shape(chord, easy)

    if shape is None:
        return f"Для аккорда {chord} пока нет схемы."

    lines = [
        f"🎸 Аккорд: {chord}",
        "",
        "Струны: E A D G B e",
        "Лады:   " + " ".join(shape),
        "",
        "X — не играть",
        "0 — открытая струна",
        "Число — номер лада",
    ]

    if easy and chord in EASY_SHAPES:
        lines.extend(["", "Показан упрощённый вариант."])

    return "\n".join(lines)


def available_chords():
    """Возвращает список аккордов со схемами."""
    return sorted(CHORD_SHAPES.keys())
